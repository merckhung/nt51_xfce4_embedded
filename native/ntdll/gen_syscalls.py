"""
Auto-generates NT 5.1 (Windows XP SP1) x86 system call stubs, ntdll.def,
and ntsyscall.h from Source\\XPSP1\\NT\\base\\ntos\\ke\\services.tab.
"""

import os
import sys
import argparse
from pathlib import Path

EXTRA_EXPORTS = [
    # 5 Mandatory Kernel-to-User Entry Points
    "LdrInitializeThunk",
    "KiUserExceptionDispatcher",
    "KiUserApcDispatcher",
    "KiUserCallbackDispatcher",
    "KiRaiseUserExceptionDispatcher",
    # PE/COFF Dynamic Loader APIs
    "LdrLoadDll",
    "LdrUnloadDll",
    "LdrGetDllHandle",
    "LdrGetProcedureAddress",
    "LdrFindEntryForAddress",
    "RtlImageNtHeader",
    "RtlImageDirectoryEntryToData",
    # ELF32 Loader APIs
    "LdrLoadElfImage",
    "LdrExecuteElfImage",
    "LdrUnloadElfImage",
    # RTL String, Heap, Sync, Process, Exception & Debug APIs
    "RtlInitAnsiString",
    "RtlInitUnicodeString",
    "RtlAnsiStringToUnicodeString",
    "RtlUnicodeStringToAnsiString",
    "RtlFreeUnicodeString",
    "RtlFreeAnsiString",
    "RtlEqualUnicodeString",
    "RtlUpcaseUnicodeChar",
    "RtlInitializeCriticalSection",
    "RtlDeleteCriticalSection",
    "RtlEnterCriticalSection",
    "RtlLeaveCriticalSection",
    "RtlTryEnterCriticalSection",
    "RtlCreateHeap",
    "RtlDestroyHeap",
    "RtlAllocateHeap",
    "RtlReAllocateHeap",
    "RtlFreeHeap",
    "RtlSizeHeap",
    "RtlGetProcessHeap",
    "RtlNormalizeProcessParams",
    "RtlDeNormalizeProcessParams",
    "RtlCreateProcessParameters",
    "RtlDestroyProcessParameters",
    "RtlNtStatusToDosError",
    "RtlRaiseException",
    "RtlRaiseStatus",
    "RtlDispatchException",
    "DbgPrint",
]


def parse_services(tab_path):
    services = []
    with open(tab_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith(";"):
                continue
            parts = line.split(",")
            name = parts[0].strip()
            nargs = int(parts[1].strip()) if len(parts) > 1 and parts[1].strip() else 0
            services.append((len(services), name, nargs))
    return services


def generate_asm(services, out_path):
    lines = [
        # REUSE-IgnoreStart
        "; SPDX-License-Identifier: GPL-2.0-only",
        # REUSE-IgnoreEnd
        "; Auto-generated by gen_syscalls.py from services.tab",
        "; Windows XP SP1 (NT 5.1.2600) x86 System Call Stubs (284 services)",
        ".386p",
        ".model flat",
        "",
        "_TEXT SEGMENT DWORD PUBLIC 'CODE'",
        "ASSUME DS:FLAT, ES:FLAT, SS:NOTHING, FS:NOTHING, GS:NOTHING",
        "",
    ]
    for idx, name, nargs in services:
        stack_bytes = nargs * 4
        nt_sym = f"_Nt{name}@{stack_bytes}"
        zw_sym = f"_Zw{name}@{stack_bytes}"
        lines.append(f"ALIGN 4")
        lines.append(f"PUBLIC {nt_sym}")
        lines.append(f"PUBLIC {zw_sym}")
        lines.append(f"{nt_sym} PROC NEAR")
        lines.append(f"{zw_sym} LABEL NEAR")
        lines.append(f"    mov eax, {idx}")
        lines.append(f"    mov edx, 07FFE0300h")
        lines.append(f"    call edx")
        if stack_bytes > 0:
            lines.append(f"    ret {stack_bytes}")
        else:
            lines.append(f"    ret")
        lines.append(f"{nt_sym} ENDP")
        lines.append("")

    lines.append("_TEXT ENDS")
    lines.append("END")
    with open(out_path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")


def generate_def(services, out_path):
    lines = [
        # REUSE-IgnoreStart
        "; SPDX-License-Identifier: GPL-2.0-only",
        # REUSE-IgnoreEnd
        "; Auto-generated by gen_syscalls.py",
        "LIBRARY ntdll.dll",
        "EXPORTS",
    ]
    for exp in EXTRA_EXPORTS:
        lines.append(f"    {exp}")
    for idx, name, nargs in services:
        lines.append(f"    Nt{name}")
        lines.append(f"    Zw{name}")
    with open(out_path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")


def generate_header(services, out_path):
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    lines = [
        # REUSE-IgnoreStart
        "/* SPDX-License-Identifier: GPL-2.0-only */",
        # REUSE-IgnoreEnd
        "/* Auto-generated by gen_syscalls.py from services.tab */",
        "#ifndef _NTSYSCALL_H_",
        "#define _NTSYSCALL_H_",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "/* System Service Numbers (NT 5.1.2600 x86) */",
    ]
    for idx, name, nargs in services:
        lines.append(f"#define SYS_Nt{name} {idx}")
    lines.extend([
        "",
        "#define NT_SYSCALL_COUNT " + str(len(services)),
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif /* _NTSYSCALL_H_ */",
    ])
    with open(out_path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("services_tab", type=Path, help="services.tab from the NT dependency")
    parser.add_argument("--native-dir", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    out_asm = args.native_dir / "ntdll" / "syscalls.asm"
    out_def = args.native_dir / "ntdll" / "ntdll.def"
    out_hdr = args.native_dir / "include" / "ntsyscall.h"
    services = parse_services(args.services_tab)
    assert len(services) == 284, f"Expected 284 syscalls, found {len(services)}"
    generate_asm(services, out_asm)
    generate_def(services, out_def)
    generate_header(services, out_hdr)
    print(f"[gen_syscalls] Generated {len(services)} syscall stubs in {out_asm}")
    print(f"[gen_syscalls] Generated {out_def} and {out_hdr}")


if __name__ == "__main__":
    main()
